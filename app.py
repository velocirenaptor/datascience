import matplotlib.pyplot as plt
import networkx as nx

G = nx.Graph()

# Agrupar datos por la descripción de la reseña y el género
relaciones = (
    dataframe.groupby(['review_score_desc', 'genres'])
    .size()
    .reset_index(name='peso')
)

# Filtramos solo las 20 relaciones con más peso para que el grafo sea legible
relaciones = relaciones.nlargest(20, 'peso')

for _, row in relaciones.iterrows():
    node_review = f"Review: {row['review_score_desc']}"
    node_genre = f"Género: {row['genres']}"

    G.add_node(node_review, type='review')
    G.add_node(node_genre, type='genre')
    # Guardamos el atributo explícitamente como 'peso'
    G.add_edge(node_review, node_genre, peso=row['peso'])

# Definir colores para diferenciar nodos
color_map = []
for node in G.nodes():
    if 'Género:' in node:
        color_map.append('#FF6F61')  # Color para el género
    else:
        color_map.append('#6BAED6')  # Color para la reseña

plt.figure(figsize=(12, 8))
pos = nx.spring_layout(G, k=0.8, seed=42)

# Normalizar grosores de líneas leyendo el atributo 'peso'
max_p = (
    max([d['peso'] for u, v, d in G.edges(data=True)])
    if len(G.edges()) > 0
    else 1
)
weights = [(d['peso'] / max_p) * 6 + 1 for u, v, d in G.edges(data=True)]

# Dibujar nodos y conexiones
nx.draw_networkx_nodes(
    G, pos, node_color=color_map, node_size=1500, alpha=0.9
)
nx.draw_networkx_edges(G, pos, width=weights, alpha=0.6, edge_color='gray')
nx.draw_networkx_labels(G, pos, font_size=8, font_weight='bold')

plt.title(
    'Grafo de Red: Relación entre Tipo de Reseña y Género del Juego',
    fontsize=12,
)
plt.axis('off')
plt.tight_layout()
plt.show()