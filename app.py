# Markdown cell: ### 1.3. Top por genero
consulta_top_por_genero = """
WITH juegos_ordenados AS (
    SELECT
        genres,
        name,
        total_reviews,
        ROW_NUMBER() OVER (PARTITION BY genres ORDER BY total_reviews DESC) AS ranking
    FROM dataframe
    WHERE genres IS NOT NULL AND total_reviews > 0
)
SELECT genres, name, total_reviews
FROM juegos_ordenados
WHERE ranking <= 3
ORDER BY genres, ranking;
"""

df = duckdb.sql(consulta_top_por_genero).df()
df

